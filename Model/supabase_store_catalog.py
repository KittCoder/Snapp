class CatalogUnavailable(RuntimeError):
    pass

class SupabaseGateway:
    """No browser keys, cookies, login, or credential-bearing error messages."""
    def __init__(self, url=None, key=None):
        url = url or os.getenv('SUPABASE_URL', '')
        key = key or os.getenv('SUPABASE_SERVICE_ROLE_KEY', '')
        parsed = urlparse(url)
        if not key or parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password:
            raise CatalogUnavailable('SUPABASE_URL and server service-role key are required')
        self.base = url.rstrip('/') + '/rest/v1/'
        self.headers = {'apikey': key, 'Authorization': 'Bearer ' + key}
        self.query_count = 0
        self._lock = threading.Lock()
        self._sessions = threading.local()
    def request(self, method, table, params=None, payload=None, prefer=None):
        headers = dict(self.headers)
        if prefer: headers['Prefer'] = prefer
        try:
            with self._lock: self.query_count += 1
            # One session per bounded worker: connection reuse without sharing a
            # mutable requests.Session between concurrent store queries.
            if not hasattr(self._sessions, 'session'):
                self._sessions.session = requests.Session()
            with timing('supabase_http'):
                response = self._sessions.session.request(
                    method, self.base + table, params=params, json=payload,
                    headers=headers, timeout=(5, 45), allow_redirects=False)
            if response.status_code not in (200, 201, 204):
                error = CatalogUnavailable('Inventory database request failed (HTTP %d)' % response.status_code)
                error.catalog_http = {'http_status': response.status_code}
                try:
                    body = response.json()
                except ValueError:
                    body = None
                if isinstance(body, dict):
                    for field in ('code', 'message'):
                        if isinstance(body.get(field), (str, int)):
                            # Also redact explicit constructor credentials, not just environment values.
                            value = str(body[field])
                            for secret in self.headers.values():
                                value = value.replace(secret, '[REDACTED]')
                            value = value.replace(self.headers['apikey'], '[REDACTED]')
                            error.catalog_http['postgrest_' + field] = safe_message(value)
                raise error
            with timing('supabase_json_decode'):
                return response.json() if response.content else None
        except (requests.RequestException, ValueError):
            raise CatalogUnavailable('Inventory database unavailable') from None
    def select(self, table, params):
        with catalog_operation('supabase_rest_select', table):
            return self.request('GET', table, params=params)
    def upsert(self, table, rows):
        return self.request('POST', table, payload=rows, prefer='resolution=merge-duplicates,return=minimal')
    @timed('candidate_query')
    def candidates(self, store, version, field, values, limit):
        # These values are generated by the ontology, never passed from browser filters.
        values = sorted(set(v for v in values if v))
        if not values: return []
        if field not in ('family','subfamily','semantic_head','normalized_name'):
            raise CatalogError('Invalid candidate field')
        params = {'select':'feature_json,identity_json,source_json,source_position', 'store_id':'eq.'+store,
                  'inventory_version_id':'eq.'+version, 'order':'source_position.asc',
                  'limit':min(limit, 900)}
        if field == 'normalized_name':
            term = re.sub(r'[^\w\s-]', ' ', values[0]).strip()
            if not term: return []
            params[field] = 'ilike.*' + '*'.join(term.split()) + '*'
        else:
            params[field] = 'in.(' + ','.join('"'+v.replace('\\','\\\\').replace('"','\\"')+'"' for v in values) + ')'
        result = []
        while len(result) < limit:
            params['offset'] = len(result)
            params['limit'] = min(900, limit-len(result))
            page = self.select('store_products', params)
            result.extend(page)
            if len(page) < params['limit']: break
        return result

class CandidateCache:
    def __init__(self, client=None):
        self.client = client
        self.hits = 0
        self.misses = 0
        if self.client is None and os.getenv('REDIS_URL'):
            import redis
            self.client = redis.Redis.from_url(os.environ['REDIS_URL'], socket_connect_timeout=1,
                                               socket_timeout=1, decode_responses=True)
    def key(self, store, version, identity, override_hash):
        value = [store, version, identity, FEATURE_VERSION, override_hash, 'bounded-v1']
        return 'snapp:store-candidates:' + hashlib.sha256(json.dumps(value,sort_keys=True).encode()).hexdigest()
    @timed('redis_get')
    def get(self, key):
        try:
            value = self.client.get(key) if self.client else None
            if value is not None:
                self.hits += 1
                return json.loads(value)
        except (OSError, ValueError): pass
        except Exception:
            # Redis is optional; database errors must never be hidden here.
            pass
        self.misses += 1
        return None
    @timed('redis_set')
    def put(self, key, rows):
        if self.client:
            try: self.client.setex(key, 300, json.dumps(rows, allow_nan=False))
            except Exception: pass

class PreparedCatalogCache:
    """Bound parsed matcher state across requests, never the whole store inventory."""
    def __init__(self, max_rows=12000, max_entries=26):
        self.max_rows = max_rows
        self.max_entries = max_entries
        self.rows = 0
        self.values = OrderedDict()
        self.lock = threading.Lock()

    def get(self, key):
        with self.lock:
            value = self.values.get(key)
            if value is None:
                return None
            self.values.move_to_end(key)
            return value[0]

    def put(self, key, catalog, count):
        if count > self.max_rows:
            return
        with self.lock:
            previous = self.values.pop(key, None)
            if previous:
                self.rows -= previous[1]
            self.values[key] = (catalog, count)
            self.rows += count
            while self.rows > self.max_rows or len(self.values) > self.max_entries:
                _, (_, size) = self.values.popitem(last=False)
                self.rows -= size


class DatabaseStoreCatalog:
    def __init__(self, metadata, version_id, gateway, cache, prepared_cache=None):
        self.metadata = metadata
        self.version_id = version_id
        self.gateway = gateway
        self.cache = cache
        self.prepared_cache = prepared_cache if prepared_cache is not None else PreparedCatalogCache()
        self.lock = threading.RLock()
        self.override_hash = digest(DEFAULT_OVERRIDES_PATH) if DEFAULT_OVERRIDES_PATH.exists() else None
    @property
    def cache_version(self):
        return (self.version_id, FEATURE_VERSION)

    def current(self):
        versions = self.gateway.select('store_inventory_versions', {
            'select':'id,source_version,product_count,feature_version',
            'store_id':'eq.'+self.metadata.id, 'active':'eq.true', 'limit':2})
        current_hash = digest(DEFAULT_OVERRIDES_PATH) if DEFAULT_OVERRIDES_PATH.exists() else None
        return self.versions_current(versions, current_hash)

    def versions_current(self, versions, current_hash):
        return (len(versions)==1 and versions[0]['id']==self.version_id
                and versions[0]['source_version']==self.metadata.inventory_version
                and versions[0].get('feature_version')==FEATURE_VERSION
                and versions[0].get('product_count')==self.metadata.product_count
                and current_hash==self.override_hash)
    def request_catalog(self, recipes):
        rows = {}
        pools = {}
        def query_pool(field, values):
            # Identical predicates yield the identical bounded, ordered pool.
            # Share within a basket without combining per-ingredient limits or
            # changing any empty-pool fallback/compatibility decision.
            values = list(values)
            key = (field, tuple(values) if field=='normalized_name' else tuple(sorted(set(values))))
            if key not in pools:
                pools[key] = self.gateway.candidates(self.metadata.id, self.version_id,
                                                     field, values, POOL_LIMIT+1)
            return pools[key]
        # Query whole relevant families to retain every structurally compatible subtype.
        # Heads/subfamilies are retrieval fallbacks, never replacement correctness gates.
        for recipe in recipes:
            for line in recipe_ingredients(recipe)[1]:
                with timing('ingredient_normalization'):
                    profile = profile_from_query(line)[0]
                query = profile.ontology
                identity = asdict(query)
                # Quantity is not a candidate predicate. Keep every required
                # attribute AND the exact lexical fallback term in the key.
                identity['normalized_text'] = profile.normalized_signature or query.normalized_text
                key = self.cache.key(self.metadata.id, (self.metadata.inventory_version, self.version_id),
                                     identity, self.override_hash)
                candidates = self.cache.get(key)
                if candidates is None:
                    branches = query.alternatives or (query,)
                    families = [b.family for b in branches if b.family]
                    candidates = query_pool('family',families)
                    if len(candidates)>POOL_LIMIT:
                        # Silent truncation could change a deal winner. Fail closed instead.
                        raise CatalogUnavailable('Candidate family exceeds safe bounded pool; parity review required')
                    if not candidates:
                        candidates = query_pool('subfamily', [b.subfamily for b in branches if b.subfamily])
                    if not candidates:
                        candidates = query_pool('semantic_head', [b.semantic_head for b in branches if b.semantic_head not in (None,'unknown')])
                    if not candidates:
                        candidates = query_pool('normalized_name', [profile.normalized_signature or query.normalized_text])
                    if len(candidates)>POOL_LIMIT: raise CatalogUnavailable('Candidate pool exceeds safe limit')
                    self.cache.put(key,candidates)
                if len(candidates)>POOL_LIMIT: raise CatalogUnavailable('Cached candidate pool exceeds safe limit')
                for row in candidates:
                    source = row['source_json']
                    if self.metadata.retailer=='ctown' and (source.get('retailer')!='ctown' or source.get('store_id')!=self.metadata.store_id):
                        raise CatalogUnavailable('Cross-store candidate provenance rejected')
                    rows[row['feature_json']['product_id']] = row
                if len(rows)>BASKET_POOL_LIMIT: raise CatalogUnavailable('Basket candidate pool exceeds safe limit')
        self.last_candidate_count = len(rows)
        ordered = sorted(rows.values(),key=lambda r:r['source_position'])
        with timing('prepared_catalog_lookup'):
            # Hash complete rows as well as immutable versions. This prevents
            # reusing parsed state even if a malformed cache changes a row in place.
            row_hash = hashlib.sha256(json.dumps(ordered, sort_keys=True,
                                      separators=(',', ':'), allow_nan=False).encode()).hexdigest()
            key = (self.metadata.id, self.version_id, FEATURE_VERSION, self.override_hash, row_hash, self.metadata)
            prepared = self.prepared_cache.get(key)
        if prepared is None:
            prepared = RequestCatalog(self.metadata, ordered)
            self.prepared_cache.put(key, prepared, len(ordered))
        # BasketBuilder's recipe cache is unbounded. Retain only bounded product
        # profiles, lexical indexes and query vectors, not prior recipe payloads.
        prepared.builder()._basket_cache.clear()
        return prepared

class BoundedMortonRetriever(ProductCandidateRetriever):
    """Reuse the active MW semantic index, restricted by unchanged matcher candidate IDs."""
    def __init__(self, features):
        super().__init__()
        self._features = features
    def load_index(self):
        original = get_basket_builder().match_service.retriever
        if not original.load_index(): return False
        self._index_embeddings = original._index_embeddings
        self._index_metadata = original._index_metadata
        self.backend = original.backend
        return True

class RequestCatalog:
    @timed('row_conversion')
    def __init__(self, metadata, rows):
        self.metadata = metadata
        self._rows = {r['feature_json']['product_id']:r['source_json'] for r in rows}
        features = [r['feature_json'] for r in rows]
        retriever = BoundedMortonRetriever(features) if metadata.retailer=='morton_williams' else MemoryRetriever(features,metadata.id)
        service = ProductMatchService(retriever=retriever)
        if metadata.retailer=='morton_williams':
            # Both use the same persisted index. Reuse its version lookup instead
            # of rereading all vector metadata/embeddings for every bounded pool.
            service._product_index_version_cache = get_basket_builder().match_service.product_index_version()
        service.match_recipe_ingredients = timed('matcher_total')(service.match_recipe_ingredients)
        service._match_from_retrieval = timed('matcher_scoring')(service._match_from_retrieval)
        retriever.retrieve_product_candidates_batch = timed('candidate_retrieval')(
            retriever.retrieve_product_candidates_batch)
        retriever.query_vectors = timed('semantic_embedding')(retriever.query_vectors)
        if all('identity_json' in row for row in rows):
            def restore(data):
                values = {k:v for k,v in data.items() if k in FoodIdentity.__dataclass_fields__}
                for key in ('absence_claims','dietary_requirements','purchase_variants','evidence'):
                    values[key] = tuple(values.get(key) or ())
                values['alternatives'] = tuple(restore(v) for v in values.get('alternatives') or ())
                return FoodIdentity(**values)
            identities = IdentityCatalog([])
            for row in rows:
                feature = row['feature_json']
                if not feature.get('eligible_for_retrieval'): continue
                identity = restore(row['identity_json'])
                pid = feature['product_id']
                identities.identities[pid] = identity
                if identity.family: identities.by_family.setdefault(identity.family,set()).add(pid)
            service._identity_catalog = identities
        self._builder = BasketBuilder(service)
        self._builder.optimize_ingredient_purchase = timed(
            'deal_optimizer')(self._builder.optimize_ingredient_purchase)
    def builder(self): return self._builder
    def source_row(self, pid):
        # Preserve legacy Morton Williams comparison payload (no invented provenance).
        return None if self.metadata.retailer=='morton_williams' else self._rows.get(pid)

class DatabaseStoreRegistry:
    @timed('registry_initialization')
    def __init__(self, gateway=None, cache=None):
        with catalog_operation("supabase_gateway_initialization"):
            self.gateway = gateway or SupabaseGateway()
        with catalog_operation("redis_cache_initialization"):
            self.cache = cache or CandidateCache()
        self.stores = {}
        self.prepared_cache = PreparedCatalogCache()
        self.errors = []
        self.manifest_path = ROOT/'Model/store_catalog_manifest.json'
        self.manifest_hash = digest(self.manifest_path)
        allowed = {entry['id']:entry for entry in json.loads(self.manifest_path.read_text())}
        entries = self.gateway.select('stores', {'select':'id,metadata','verified':'eq.true','active':'eq.true','limit':14})
        versions = self.gateway.select('store_inventory_versions', {'select':'id,store_id,source_version,product_count,feature_version',
                                      'active':'eq.true','limit':14})
        by_store = {v['store_id']:v for v in versions}
        if len(entries)>13 or len(by_store)!=len(versions): raise CatalogUnavailable('Invalid active inventory registry')
        if {entry['id'] for entry in entries} != set(allowed):
            raise CatalogUnavailable('Database inventory set differs from verified whitelist')
        for entry in entries:
            version = by_store.get(entry['id'])
            if not version or version.get('feature_version') != FEATURE_VERSION:
                raise CatalogUnavailable('Inventory feature version is unavailable or stale')
            metadata = StoreMetadata(**entry['metadata'])
            if (metadata.id!=entry['id'] or metadata.inventory_version!=version['source_version']
                    or metadata.product_count!=version['product_count']):
                raise CatalogUnavailable('Inventory metadata/version mismatch')
            if metadata.public()!=allowed[metadata.id]:
                raise CatalogUnavailable('Verified store identity/source version mismatch')
            self.stores[metadata.id] = DatabaseStoreCatalog(metadata,version['id'],self.gateway,self.cache,self.prepared_cache)
        if not self.stores: raise CatalogUnavailable('No verified database inventories available')
    def select(self, ids):
        if digest(self.manifest_path)!=self.manifest_hash:
            raise CatalogUnavailable('Verified inventory manifest changed; reload registry')
        if not isinstance(ids,list) or not 1<=len(ids)<=13 or any(not isinstance(i,str) or i not in self.stores for i in ids):
            raise CatalogError('Choose only available verified stores')
        return [self.stores[i] for i in dict.fromkeys(ids)]
    @timed('active_inventory_versions')
    def current_catalogs(self, catalogs):
        # A fresh single read on EVERY request, including completed-basket hits.
        # A TTL on mutable active versions would allow stale products/results.
        versions = self.gateway.select('store_inventory_versions', {
            'select':'id,store_id,source_version,product_count,feature_version',
            'active':'eq.true', 'limit':14})
        by_store = {}
        for version in versions:
            by_store.setdefault(version['store_id'], []).append(version)
        current_hash = digest(DEFAULT_OVERRIDES_PATH) if DEFAULT_OVERRIDES_PATH.exists() else None
        return [c for c in catalogs if c.versions_current(by_store.get(c.metadata.id, []), current_hash)]

    def all_current(self, catalogs):
        return len(self.current_catalogs(catalogs)) == len(catalogs)

    def public(self):
        catalogs = self.select(list(self.stores))
        return [c.metadata.public() for c in self.current_catalogs(catalogs)]

def configured_registry():
    backend = os.getenv('STORE_CATALOG_BACKEND', 'file').lower()
    if backend not in ('auto','file','supabase'): raise CatalogUnavailable('Invalid STORE_CATALOG_BACKEND')
    if backend=='file': return StoreRegistry()
    if backend=='supabase': return DatabaseStoreRegistry()
    production = (os.getenv('SNAPP_ENV', os.getenv('FLASK_ENV', '')).lower()=='production'
                  or os.getenv('RENDER', '').lower()=='true')
    if production: return DatabaseStoreRegistry()
    if os.getenv('SUPABASE_SERVICE_ROLE_KEY'):
        try: return DatabaseStoreRegistry()
        except CatalogUnavailable: pass
    return StoreRegistry()
